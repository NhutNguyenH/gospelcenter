#!/usr/bin/env node
// regen-translations-js.js — rebuild translations.js from translations.json.
//
// Usage:  node tools/regen-translations-js.js
//
// Byte-compatible with writeOutputs() in translate-gemini.js: sorted keys,
// 2-space JSON, atomic write via .tmp + rename. Use this after hand-editing
// translations.json — it is ~1000x cheaper than re-running /translate, and it
// cannot re-translate (and thus cannot clobber) anything.
//
// Exits non-zero if translations.json is invalid or empty, so the caller never
// ships a broken file.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'translations.json');
const JS_PATH = path.join(ROOT, 'translations.js');
const HEADER = '// Auto-generated by translate-gemini.js. KHÔNG sửa tay — chỉnh strings/*.json rồi chạy lại.\n';

function fail(msg) {
  process.stderr.write('ERROR: ' + msg + '\n');
  process.exit(1);
}

let raw;
try {
  raw = fs.readFileSync(JSON_PATH, 'utf8');
} catch (e) {
  fail(`cannot read translations.json — ${e.message}`);
}
if (!raw.trim()) {
  fail('translations.json is EMPTY (0 bytes). Recover it from translations.js before continuing — ' +
       'parse window.WIDGET_TRANSLATIONS out of translations.js. Do NOT overwrite.');
}

let translations;
try {
  translations = JSON.parse(raw);
} catch (e) {
  fail(`translations.json is not valid JSON — ${e.message}. Fix the syntax; nothing was written.`);
}
if (!translations || typeof translations !== 'object' || Array.isArray(translations)) {
  fail('translations.json must be a JSON object of { key: { en, vi, no } }.');
}

const keys = Object.keys(translations);
if (keys.length === 0) fail('translations.json has 0 entries — refusing to write an empty translations.js.');

// Shape validation. Incomplete entries are a warning, not a failure: the widget
// falls back to restoring the original HTML when a field is missing.
const incomplete = [];
for (const k of keys) {
  const e = translations[k];
  if (!e || typeof e !== 'object' || Array.isArray(e)) {
    fail(`entry ${JSON.stringify(k.slice(0, 60))} is not an object.`);
  }
  const missing = ['en', 'vi', 'no'].filter((f) => typeof e[f] !== 'string' || !e[f]);
  if (missing.length) incomplete.push({ key: k, missing });
}

const sorted = Object.fromEntries(keys.sort().map((k) => [k, translations[k]]));

// Rewrite the JSON too, so key order stays stable and git diffs stay minimal.
const jsonBody = JSON.stringify(sorted, null, 2);
fs.writeFileSync(JSON_PATH + '.tmp', jsonBody, 'utf8');
fs.renameSync(JSON_PATH + '.tmp', JSON_PATH);

const jsBody = HEADER + 'window.WIDGET_TRANSLATIONS = ' + jsonBody + ';\n';
fs.writeFileSync(JS_PATH + '.tmp', jsBody, 'utf8');
fs.renameSync(JS_PATH + '.tmp', JS_PATH);

console.log(`OK  translations.json  ${keys.length} entries, ${Buffer.byteLength(jsonBody)} bytes`);
console.log(`OK  translations.js    ${Buffer.byteLength(jsBody)} bytes`);

if (incomplete.length) {
  console.log(`\nWARN  ${incomplete.length} entry/entries missing a language field:`);
  for (const it of incomplete.slice(0, 10)) {
    console.log(`  - ${JSON.stringify(it.key.slice(0, 70))} missing: ${it.missing.join(', ')}`);
  }
  if (incomplete.length > 10) console.log(`  … and ${incomplete.length - 10} more`);
}
